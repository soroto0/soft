import React from 'react';
import { AbsoluteFill, useCurrentFrame, useVideoConfig, interpolate, Easing } from 'remotion';

// Общая подложка ВСЕХ сцен. Без неё сцена — плоская заливка #07090c на семь
// секунд, и посреди документального ролика это читается как провал в чёрное,
// как будто кончился материал. Живой фон делает три вещи, и все три дешёвые:
//
//   * медленный градиентный «свет» — уводит от идеально ровного чёрного;
//   * пылинки в луче — в проекте это стандарт для всех роликов и каналов,
//     сцена не должна из него выпадать;
//   * зерно и виньетка — сцена садится на ту же плёнку, что и съёмка рядом.
//
// Всё детерминировано: позиции пылинок считаются из индекса, а не из
// Math.random, иначе повторный рендер дал бы другую картинку.
// ДНО ЯРКОСТИ. Раньше здесь стоял #06080b — это 8 из 255, то есть почти
// чистый чёрный, и виньетка гасила края ещё на 55%. Замер готового ролика
// (estoico-es, 2026-08-07): схема «Niveles del infinito» занимает секунды
// 19.7-30.8, средняя яркость участка 2.7 из 255. Одиннадцать секунд чёрного
// прямоугольника с волосяными белыми линиями — ровно там, где кривая
// удержания теряет 28% зрителей. Таких провалов в ролике двадцать, суммарно
// четыре минуты; самый длинный — 28 секунд.
//
// Для сравнения, ролик-образец той же ниши (1.24 млн просмотров) уходит в
// чёрное 56 раз, но каждый раз на ОДНУ секунду: у него это переход, а не
// сцена. Средняя яркость по ролику у него 60, в первые 30 секунд — 44.
//
// Поэтому дно поднято до ~40 и виньетка ослаблена. Кадр остаётся тёмным и
// документальным, но перестаёт быть дырой.
const BASES: Record<string, string> = {
  // Почерк канала задаёт ТОН дна, а не только акцент: разбор катастроф
  // сидит в холодной стали, бытовой канал — в тёплом дереве, размышление —
  // в глубоком сине-зелёном. Один цвет на все каналы был ещё одной
  // причиной, по которой они «монтируются одинаково».
  // Числа подобраны замером, а не на глаз: первая попытка (#1b2026 и
  // соседние) дала на готовом клипе 28.6, то есть порог «не темнее 25»
  // проходился впритык, без запаса на виньетку и цветокор. Эти дают ~45 —
  // столько же, сколько у ролика-образца в первые тридцать секунд.
  harsh: '#2b3138',
  warm: '#352b21',
  contemplative: '#232d33',
};
const BASE_DEFAULT = '#2a3037';

export const Backdrop: React.FC<{
  accent?: string; opacity?: number; look?: string;
}> = ({ accent = '#e0b44c', opacity = 1, look = '' }) => {
  const base = BASES[(look || '').trim().toLowerCase()] || BASE_DEFAULT;
  const frame = useCurrentFrame();
  const { fps, width, height } = useVideoConfig();
  const t = frame / fps;

  // 46 пылинок: меньше — не читается, больше — превращается в шум
  const motes = Array.from({ length: 46 }, (_, i) => {
    // псевдослучайно, но воспроизводимо: тригонометрия от индекса
    const sx = (Math.sin(i * 12.9898) * 43758.5453) % 1;
    const sy = (Math.sin(i * 78.233) * 12345.6789) % 1;
    const sp = 0.25 + Math.abs((Math.sin(i * 3.17) % 1)) * 0.7;
    const x = ((Math.abs(sx) + t * 0.012 * sp) % 1) * width;
    // пылинки медленно поднимаются, как в тёплом воздухе
    const y = ((Math.abs(sy) - t * 0.018 * sp) % 1 + 1) % 1 * height;
    const r = 1.1 + Math.abs(Math.sin(i * 5.7)) * 2.2;
    const a = 0.10 + Math.abs(Math.sin(i * 2.3 + t * 0.9)) * 0.30;
    return { x, y, r, a };
  });

  const glow = interpolate(frame, [0, Math.round(fps * 1.2)], [0, 1], {
    easing: Easing.out(Easing.cubic),
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  // «Свет» очень медленно ходит по кадру — за семь секунд проходит немного,
  // но глаз ловит, что кадр живой.
  const lx = 42 + Math.sin(t * 0.22) * 9;
  const ly = 34 + Math.cos(t * 0.17) * 7;

  return (
    <AbsoluteFill style={{ opacity }}>
      <AbsoluteFill style={{ background: base }} />
      {/* мягкий свет */}
      <AbsoluteFill style={{
        opacity: 0.55 * glow,
        background: `radial-gradient(ellipse 62% 58% at ${lx}% ${ly}%, `
          + `rgba(70,96,120,0.42) 0%, rgba(20,30,42,0.18) 45%, rgba(0,0,0,0) 72%)`,
      }} />
      {/* акцентная подсветка снизу — связывает сцену с палитрой ролика */}
      <AbsoluteFill style={{
        opacity: 0.16 * glow,
        background: `radial-gradient(ellipse 80% 40% at 50% 108%, ${accent} 0%, `
          + `rgba(0,0,0,0) 62%)`,
      }} />

      <svg width="100%" height="100%" style={{ position: 'absolute', inset: 0 }}>
        {motes.map((m, i) => (
          <circle key={i} cx={m.x} cy={m.y} r={m.r}
                  fill="rgba(226,238,246,1)" opacity={m.a * glow} />
        ))}
      </svg>

      {/* Виньетка — сажает сцену на ту же плёнку, что и съёмка. Ослаблена с
          0.55 до 0.32: при поднятом дне прежняя сила снова утаскивала края
          в чёрное, и весь смысл поднятия терялся — середина светлела, а
          средняя яркость кадра оставалась низкой. */}
      <AbsoluteFill style={{
        background: 'radial-gradient(ellipse 78% 74% at 50% 48%, '
          + 'rgba(0,0,0,0) 46%, rgba(0,0,0,0.32) 100%)',
      }} />
    </AbsoluteFill>
  );
};
