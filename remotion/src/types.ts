// Общие типы для ядра (Overlay.tsx) и для сгенерированных вариантов
// (variants/*.tsx). Вынесены в отдельный файл намеренно: варианты не могут
// импортировать тип из Overlay.tsx, потому что Overlay.tsx сам импортирует
// реестр вариантов — получился бы цикл.

export type OverlayProps = {
  type: string;
  content: string;
  pos: string;
  dur: number;
  fps?: number;
  width?: number;
  height?: number;
  img?: string;
  items?: { label: string; img: string }[];
  variant?: string;
};

// Что получает КАЖДЫЙ вариант из библиотеки. exit/enter уже посчитаны ядром
// (useExit/useEnter в Overlay.tsx) — вариант не считает их сам, иначе тайминг
// появления/ухода разъедется с остальными оверлеями в ролике.
//   enter: 0→1 за первые 0.4с
//   exit:  1→0 за последние 0.3с от p.dur
// Оба надо умножать в opacity своих слоёв, иначе оверлей моргнёт при склейке.
export type VariantProps = OverlayProps & { exit: number; enter: number };

// Обложка для YouTube. Отдельный тип, а не вариант оверлея: у неё
// противоположные требования — непрозрачный фон на весь кадр и кегль,
// читаемый в ленте шириной ~210px.
//   headline — текст, перевод строки = новая строка в макете
//   bg       — путь к картинке относительно remotion/public, или http-URL
//   layout   — 'left' | 'bottom' | 'split'
//   style    — палитра канала: 'harsh' | 'warm' | 'contemplative'. То же
//              поле, по которому render.PALETTES выбирает склейки, и по той
//              же причине: обложка — обещание того, что внутри, и канал,
//              который рубит склейками, не может обещать созерцание. Без
//              этого поля все каналы рисовались одним макетом — золотая
//              рамка + Arial Black капсом, — и отличались только словами.
//   sub      — подзаголовок мельче заголовка (вторая ступень кегля)
//   badges   — столбик выгод с галочками, только у продающего канала
//   ribbon   — нижняя лента из трёх пунктов, там же
//   focusX/Y — где в кадре стоит предмет разговора, в процентах. Туда
//              смотрит стрелка, туда же наведена зум-врезка и свечение.
//              Точку называет та же модель, что придумала фон, — иначе
//              стрелка указывала бы в случайное место.
export type ThumbnailProps = {
  headline: string;
  bg?: string;
  accent?: string;
  layout?: string;
  style?: string;
  sub?: string;
  badges?: string[];
  ribbon?: string[];
  focusX?: number;
  focusY?: number;
};

// СЦЕНА — не оверлей. Занимает кадр целиком и заменяет собой съёмку там,
// где снимать нечего: планета, карта, схема узла, ход процесса. Оверлеи
// ложатся поверх видео, сцена сама и есть видео этого плана.
//   kind   — какую сцену рисовать (globe, map, ...)
//   title  — подпись в кадре, обычно ключевая фраза из закадрового текста
//   lat/lon — точка, если сцена про место
//   items  — данные сцены: этапы, узлы, значения
//   bare   — рисовать БЕЗ общей подложки Backdrop. Нужно только приёмке в
//            gen_scenes.py: она считает цвета и движение по пикселям, и живой
//            фон (градиент, пылинки, зерно) сам по себе даёт и то и другое —
//            заглушка, не нарисовавшая ничего, прошла бы проверку. С bare
//            измеряется ровно то, что нарисовала сама сцена. В ролике этот
//            флаг не выставляется никогда.
export type SceneProps = {
  kind: string;
  title?: string;
  lat?: number;
  lon?: number;
  items?: string[];
  dur: number;
  exit: number;
  enter: number;
  bare?: boolean;
  // Почерк канала (harsh | warm | contemplative) и его акцентный цвет.
  // По ним подложка сцены выбирает тон дна: без них схемы всех каналов
  // рисовались на одном фоне — ещё одна причина, по которой каналы
  // «монтировались одинаково».
  look?: string;
  accent?: string;
};
