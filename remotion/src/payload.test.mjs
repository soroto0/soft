// Проверка разбора чисел в плашках. Строки взяты из настоящих overlays.txt
// работающих каналов, а не выдуманы.
import { parseAmount, formatAmount } from './payload.ts';

const случаи = [
  // [вход, значение, знаков после запятой, что должно стоять в кадре]
  ['30.000', 30000, 0, '30.000'],   // немецкий: точка = тысячи (тот самый сбой)
  ['1.234.567', 1234567, 0, '1.234.567'],
  ['1,200', 1200, 0, '1,200'],      // английский: запятая = тысячи
  ['300', 300, 0, '300'],
  ['2', 2, 0, '2'],
  ['1.5', 1.5, 1, '1.5'],           // десятичная точка
  ['2,5', 2.5, 1, '2,5'],           // десятичная запятая (немецкий)
  ['1.234,5', 1234.5, 1, '1.234,5'],
  ['1,234.5', 1234.5, 1, '1,234.5'],
  ['0.500', 500, 0, '500'],         // осознанно: три цифры = тысячи
  ['12.000.000', 12000000, 0, '12.000.000'],
  ['200,000', 200000, 0, '200,000'],
];

let плохо = 0;
for (const [вход, знач, зн, вид] of случаи) {
  const r = parseAmount(вход);
  const вышло = formatAmount(r.value, r.decimals, r.group);
  const ок = r.value === знач && r.decimals === зн && вышло === вид;
  if (!ок) плохо++;
  console.log(
    `${ок ? 'ок  ' : 'СБОЙ'} ${вход.padEnd(12)} -> ${String(r.value).padEnd(10)}`
    + ` знаков ${r.decimals}  в кадре «${вышло}»`
    + (ок ? '' : `   ЖДАЛИ ${знач} / ${зн} / «${вид}»`),
  );
}
console.log(плохо ? `\nсбоев: ${плохо}` : '\nвсе случаи прошли');
process.exit(плохо ? 1 : 0);
