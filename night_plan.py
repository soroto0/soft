# -*- coding: utf-8 -*-
"""Планировщик ночи: что делать, в каком порядке и сколько на это дать.

Отдельный модуль, а не кусок autopilot.py, по двум причинам.

Первая — его можно ЗАПУСТИТЬ И ПРОВЕРИТЬ. autopilot.py импортирует webapp, а
тот на импорте тянет gen_remotion_gemini, который переписывает Overlay.tsx и
ходит в платный API. То есть проверить расписание ночи всухую было нельзя в
принципе: любой тест начинал бы с побочных действий. Здесь только stdlib и
channels.py, импорт ничего не делает.

Вторая — у ночи два входа: кнопка «Автопилот на ночь» (webapp.Api.autopilot) и
python autopilot.py. Пока расчёт жил в autopilot.py, а решение принимал webapp,
пути расходились по мелочи: в ночь 2026-08-03 кнопка не сбрасывала между
каналами бюджет ожидания лимита Veo, потому что все каналы шли одной задачей.
Теперь оба входа спрашивают одну и ту же функцию.


ГЛАВНАЯ ПЕРЕМЕНА: НЕЗАКОНЧЕННЫЙ РОЛИК ТЕПЕРЬ ДОДЕЛЫВАЮТ, А НЕ БРОСАЮТ

Раньше каждый заход заводил НОВУЮ папку с датой, и логика была честной: раз
переиспользовать нечего, оборванный ролик — потерянные часы, значит лучше не
начинать то, что не успеешь. Из этого росли и пропуск каналов по времени, и
завышенная оценка времени.

К 2026-08-04 переиспользуется практически всё, и это видно в app.log:
    [Возобновление] на диске: script.txt, audio/voiceover.mp3,
        subs/voiceover.srt; ИИ-кадров 97 — они переиспользуются
    [Раскадровка] Запросы к кадрам взяты из прошлого прогона (92 шт.) —
        имена файлов совпадут, готовые кадры переиспользуются
    [Раскадровка] Уже готово с прошлого прогона: 76 кадр(ов)
Плюс озвучка (audio/.voice_stamp) и секвенции оверлеев (.overlay.json).

Значит доделать брошенный ролик стоит минут, а не часов, и платить за «не
успею» пропуском целого канала больше незачем. Ночь 2026-08-03 — цена старого
поведения: abyss убит сторожем на 53%, The Home Vault не доехал, третий канал
не начинался, к утру ноль роликов, и оба огрызка лежали мёртвым грузом.
"""
import json
import os
import time
from datetime import datetime
from pathlib import Path

import channels as channels_mod

BASE = Path(__file__).resolve().parent

# Сколько РЕАЛЬНО занимает минута готового видео. Замер по app.log, по
# прогонам, дошедшим до конца («✔ Генерация видео: завершено за N c» с
# известным каналом):
#   2026-08-01 17:04  The Home Vault, 20 мин видео, 4.90 ч  -> 882 c/мин
#   2026-07-30 00:24  The Home Vault, 20 мин видео, 2.19 ч  -> 394 c/мин
# Берём худший и округляем вверх: 900. Прежние 1800 были не замером, а
# перестраховкой после ночи 2026-08-03, и завышали вдвое.
#
# Цена ошибки в этом числе теперь низкая: по нему больше НЕ решается, делать
# канал или нет (каналы не пропускаются). Оно нужно только для сводки и как
# верхняя граница доли времени.
SEC_PER_VIDEO_MINUTE = float(os.getenv("AUTOPILOT_SEC_PER_MIN", "900"))

# Сколько часов у ночи. Делится между каналами, чтобы каждый получил свой
# кусок, а не первый съел всё.
NIGHT_H = float(os.getenv("AUTOPILOT_NIGHT_H", "10"))

# Меньше этого куска давать каналу бессмысленно: по замеру 2026-08-03 сценарий,
# озвучка и субтитры занимают вместе ~7 минут, а дальше идёт раскадровка,
# которой нужны часы. Полчаса — это ролик, не сдвинувшийся дальше субтитров.
MIN_SLICE_S = 1.5 * 3600

# Сторож ТИШИНЫ. Главный инструмент против зависания — именно он, а не общий
# потолок: настоящие зависания в журнале выглядят как полная тишина в идущей
# задаче.
#   2026-08-02 04:48 -> 13:21  8.5 ч молчания после «План 262 -> OK»
#   2026-08-03 00:50 -> 12:12  11.3 ч молчания сразу после «▶ запущено»
# Самая длинная ЗАКОННАЯ пауза за тот же период — 20.0 мин (ожидание лимита
# картинок VeoNonStop, у него свой бюджет). 45 минут — это она с запасом
# больше чем вдвое, и при этом в 11 раз короче настоящего зависания.
# Сходится и со вторым источником: is_busy.py, который отвечает на вопрос
# «можно ли перезапускать приложение», считает предельной тишиной 15 минут
# (самая молчаливая стадия — Whisper, около пяти минут). Здесь порог втрое
# выше, потому что цена ошибки разная: там она стоит оборванного прогона,
# здесь — только перехода к следующему каналу.
STALL_S = float(os.getenv("AUTOPILOT_STALL_S", str(45 * 60)))

# Как часто сторож просыпается и смотрит на пульс. Отдельная величина, а не
# число внутри цикла, — чтобы проверка могла прогнать сторожа за секунды, а не
# ждать реальные 45 минут: сторож, которого нельзя проверить, ничем не лучше
# отсутствующего (прежний, на threading.Timer, так и не был проверен ни разу и
# не останавливал ffmpeg вовсе).
GUARD_POLL_S = float(os.getenv("AUTOPILOT_GUARD_POLL_S", "10"))

# Сколько ночей подряд возвращаться к одному и тому же незаконченному ролику.
# Без предела ролик, который падает по системной причине (нет ключа, битый
# сценарий), запирал бы канал навсегда: каждую ночь автопилот доделывал бы
# именно его и каждую ночь падал бы на том же месте. После трёх попыток
# отступаем и начинаем с чистой папки, а старую НЕ трогаем — она остаётся на
# диске для разбора.
MAX_RESUME = int(os.getenv("AUTOPILOT_MAX_RESUME", "3"))

# Насколько старый брошенный ролик ещё имеет смысл доделывать. Неделя.
# Меньше нельзя: пропустить пару ночей — обычное дело, а ролик, брошенный
# позавчера, доделывается за минуты. Больше нельзя тоже: тема уже записана в
# used_topics, разбор ниши с тех пор сменился, и доделанный через месяц ролик
# выйдет не по той формуле, по которой его задумывали. На настоящих данных
# порог отсекает мусор вроде home-vault/test1 (2026-07-25) и не трогает
# вчерашние огрызки.
MAX_RESUME_AGE_D = float(os.getenv("AUTOPILOT_MAX_RESUME_AGE_D", "7"))

# Файл с отметками автопилота внутри папки ролика. Отдельный от meta.json:
# meta.json пишет цепочка, и класть туда служебный счётчик попыток — значит
# рисковать им при каждой правке цепочки.
MARK = ".autopilot.json"

# Из чего складывается время ролика, долями. Замер той же ночи 2026-08-03
# (abyss, 13 мин): сценарий 2.3 мин, озвучка 1.6, субтитры 2.5, раскадровка
# ~3 ч, рендер ~25 мин. Нужно, чтобы оценить ОСТАТОК работы по начатому
# ролику: доделать почти готовый и начать с нуля — это разные заявки на время.
STAGES = (
    ("script.txt", "сценарий", 0.02),
    ("audio/voiceover.mp3", "озвучка", 0.03),
    ("subs/voiceover.srt", "субтитры", 0.03),
    ("timeline.json", "раскадровка", 0.75),
    ("output_final.mp4", "рендер", 0.17),
)


def fresh_for_script(d: Path, rel: str) -> bool:
    """Сделан ли этот артефакт под сценарий, который ЛЕЖИТ В ПАПКЕ СЕЙЧАС.

    Рабочая папка у канала одна на все его ролики, и озвучка, субтитры,
    раскадровка от прошлого ролика остаются на диске. По одному .exists()
    отличить их от своих нельзя — а разница дорогая: 04.08 в home-vault
    лежали timeline.json и sequence.xml от 01.08 при сценарии от 04.08, и
    автопилот считал раскадровку (0.75 всей работы) сделанной. Ролику,
    который надо собирать с нуля, доставалась четверть нужного времени, и
    сторож обрывал его на середине.

    Признак — время правки: всё, что делается ПО сценарию, делается ПОСЛЕ
    него. Отдельный отпечаток тут не нужен и даже вреден — его пришлось бы
    заводить каждому шагу и хранить в meta.json, а время правки уже есть у
    любого файла, в том числе у папок, собранных прошлыми версиями софта.
    Условие на save_script: он не переписывает файл с тем же текстом, иначе
    время сценария обновлялось бы на каждом прогоне и всё готовое считалось
    бы чужим (а это час платных ИИ-кадров заново).

    Секунда допуска — на разное разрешение времени у файловых систем.
    """
    try:
        s = (d / "script.txt").stat().st_mtime
    except OSError:
        return True        # сценария нет — сравнивать не с чем, не мешаем
    try:
        return (d / rel).stat().st_mtime >= s - 1
    except OSError:
        return False


def _has(d: Path, rel: str) -> bool:
    """Есть ли готовый артефакт этого шага — И ОТНОСИТСЯ ЛИ ОН К ЭТОМУ РОЛИКУ.

    Для output_final.mp4 спрашиваем is_finished, а не просто .exists(): на
    настоящих данных в корне abyss лежит output_final.mp4 нулевой длины от
    оборванного ffmpeg, и по одному наличию файла сводка бодро сообщала бы
    «сделано: … рендер» про ролик, которого нет.
    """
    if rel == "output_final.mp4":
        # готовый ролик тоже бывает от ПРОШЛОГО сценария: тогда он не «шаг
        # сделан», а просто лежащий рядом старый файл
        return is_finished(d) and fresh_for_script(d, rel)
    try:
        if rel == "script.txt":
            return (d / rel).exists()   # сам себе точка отсчёта
        return (d / rel).exists() and fresh_for_script(d, rel)
    except OSError:
        return False


def is_finished(d: Path) -> bool:
    """Ролик доведён до конца — есть непустой output_final.mp4.

    Проверяем РАЗМЕР, а не только наличие: оборванный ffmpeg оставляет файл
    нулевой длины, и по одному .exists() такой огрызок считался бы готовым
    роликом — канал был бы «сделан» и больше не доделывался бы никогда.
    """
    out = d / "output_final.mp4"
    try:
        return out.exists() and out.stat().st_size > 1_000_000
    except OSError:
        return False


def stage_of(d: Path, channel: dict | None = None) -> str:
    """На чём остановился незаконченный ролик — словами для утренней сводки.

    Утром по папке видно только «файла нет». Разница между «умер на сценарии»
    (значит, беда с ключами LLM) и «стоит перед рендером» (значит, доделается
    за двадцать минут) решает, что человеку делать дальше.
    """
    short = script_too_short(d, channel) if channel is not None else ""
    if short:
        # Не перечисляем «сделано: сценарий, озвучка, раскадровка» про работу,
        # которая через минуту после старта станет чужой — иначе сводка врёт
        # человеку ровно там, где он по ней принимает решение.
        return short
    done = [name for rel, name, _ in STAGES if _has(d, rel)]
    if not done:
        return "пусто — не начинался"
    return "сделано: " + ", ".join(done)


# Сколько слов сценария приходится на минуту готового ролика. Замер, а не
# оценка: у собранного abyss/2026-08-04 сценарий 2320 слов при видео 14.3 мин.
WORDS_PER_MINUTE = 162
# Ниже какой доли от нужного объёма сценарий считается чужим. 0.6 — с запасом
# вниз: настоящий сценарий abyss дал 110% от расчёта, а найденные обрезки — 27%
# (home-vault) и 11% (estoico-es). Между группами огромный зазор.
SCRIPT_MIN_RATIO = 0.6


def script_too_short(d: Path, channel: dict | None) -> str:
    """Сценарий в папке заведомо не для этого канала — короче, чем нужно.

    Пустая строка — сценарий годится.

    Зачем в ПЛАНИРОВЩИКЕ, а не только в цепочке. Цепочка такой сценарий
    отвергает и пишет новый (webapp._stale_script), но происходит это уже в
    прогоне. Планировщик же считает бюджет ДО старта — и, глядя на короткий
    сценарий и собранные по нему озвучку с раскадровкой, честно решал, что
    работы осталось на полтора часа. На деле после замены сценария вся эта
    работа становится чужой, и ролик идёт почти с нуля.
    Замер на настоящих данных: estoico-es с 633 словами при заявленных 35
    минутах оценивался в 1.7 ч вместо ~8.8 ч, и ночь распределялась по этой
    выдумке — короткий канал шёл первым и съедал время того, который реально
    мог успеть.
    """
    mins = int((channel or {}).get("minutes") or 0)
    if not mins:
        return ""
    try:
        words = len((d / "script.txt").read_text(
            encoding="utf-8", errors="ignore").split())
    except OSError:
        return ""
    if not words:
        return ""
    need = mins * WORDS_PER_MINUTE
    if words >= need * SCRIPT_MIN_RATIO:
        return ""
    return (f"сценарий в папке на {words / WORDS_PER_MINUTE:.0f} мин, "
            f"а канал на {mins} мин — цепочка перепишет его, и всё "
            f"сделанное по нему станет чужим")


def done_fraction(d: Path, channel: dict | None = None) -> float:
    """Какая доля работы по ролику уже лежит на диске, от 0 до 1.

    channel нужен, чтобы отличить «работа сделана» от «работа сделана по
    сценарию, который сейчас же будет выброшен» — см. script_too_short.
    """
    if channel is not None and script_too_short(d, channel):
        return 0.0
    return sum(w for rel, _, w in STAGES if _has(d, rel))


def estimate_s(channel: dict, project: Path | None = None) -> float:
    """Сколько ПРИМЕРНО осталось работы по этому ролику.

    Для начатого проекта — ОСТАТОК, а не полная длина: доделать ролик, у
    которого готовы сценарий, озвучка и сто ИИ-кадров, — это минуты, и
    выдавать его за полноценный ролик в сводке значит врать самому себе.
    """
    full = float(channel.get("minutes") or 12) * SEC_PER_VIDEO_MINUTE
    if project is None:
        return full
    return full * max(0.05, 1.0 - done_fraction(project, channel))


def fits(channel: dict, left_s: float, project: Path | None = None) -> bool:
    """Успеем ли доделать в оставшееся время. Только для режима --fit.

    По умолчанию НЕ применяется. Смысл был в том, что оборванный ролик —
    выброшенные часы; теперь он доделывается следующей ночью, поэтому пропуск
    канала стоит дороже обрыва. Ключ оставлен на случай, когда нужен именно
    готовый ролик к утру или ничего.
    """
    return estimate_s(channel, project) * 1.15 <= left_s


def budget_for(channel: dict, left_s: float = 0.0, channels_left: int = 1,
               project: Path | None = None) -> float:
    """Сколько времени дать одному ролику.

    Потолок теперь защищает от ЗАВИСАНИЯ и от того, что один канал съест ночь,
    а не решает «влезет / не влезет». Отсюда три границы:

      * честная доля от остатка ночи — чтобы очередь дошла до каждого канала.
        Ночь 2026-08-03 умерла именно так: abyss получил 3.6 ч, The Home Vault
        5.5 ч, а третий канал не начинался вовсе;
      * не больше полутора оценок — сверх этого канал уже не работает, а висит;
      * не меньше MIN_SLICE_S — иначе кусок настолько мал, что ролик не
        сдвинется дальше субтитров, и ночь пройдёт впустую при формально
        «поработавших» каналах.

    Переменная окружения AUTOPILOT_MAX_VIDEO_S перебивает всё: если человек
    задал потолок руками, значит он знает, чего хочет.
    """
    forced = float(os.getenv("AUTOPILOT_MAX_VIDEO_S", "0"))
    if forced > 0:
        return forced
    cap = estimate_s(channel, project) * 1.5
    if left_s > 0 and channels_left > 0:
        cap = min(cap, left_s / channels_left)
    return max(MIN_SLICE_S, cap)


# ---------- выбор папки ролика ----------

def _root_of(channel: dict) -> Path:
    root = channels_mod.projects_dir(channel)
    if not root.is_absolute():
        root = BASE / root
    return root


def attempts(d: Path) -> int:
    try:
        return int(json.loads((d / MARK).read_text(encoding="utf-8"))
                   .get("attempts", 0))
    except (OSError, ValueError, TypeError, AttributeError):
        return 0


def note_attempt(d: Path, note: str = "") -> None:
    """Отметить в самой папке, что автопилот брался за этот ролик.

    Счётчик живёт В ПАПКЕ, а не в общем файле: папку можно унести, переименовать
    или удалить, и счётчик уйдёт вместе с ней — общий список неизбежно
    рассыпался бы на путях, которых уже нет.
    """
    data = {"attempts": attempts(d) + 1,
            "last": datetime.now().isoformat(timespec="seconds"),
            "note": note}
    try:
        d.mkdir(parents=True, exist_ok=True)
        (d / MARK).write_text(json.dumps(data, ensure_ascii=False, indent=2),
                              encoding="utf-8")
    except OSError:
        pass          # отметка полезная, но не настолько, чтобы ронять ночь


def is_empty_shell(d: Path) -> bool:
    """Папка есть, а ролика в ней нет вообще — ни сценария, ни кадров.

    Такую оставляет ролик, упавший на самом первом шаге (не дали тему, лёг
    ключ LLM). Доделывать в ней нечего, но и городить рядом новую незачем.
    Свой служебный .autopilot.json за содержимое не считаем.
    """
    return done_fraction(d) == 0 and not (d / "output_final.mp4").exists()


def _new_dir(root: Path, stamp: str, taken: set) -> Path:
    """Свободная папка под сегодняшнюю дату: 2026-08-04, потом _2, _3.

    Занятой считается всякая, где что-то ЛЕЖИТ. Раньше занятой считалась любая
    существующая, даже пустая, — и канал, падающий на первом же шаге, каждую
    ночь оставлял по новой пустой папке: 2026-08-04, _2, _3, и так до
    бесконечности. Ложиться поверх пустой безопасно: перезаписывать в ней
    нечего.
    """
    d = root / stamp
    i = 1
    while d.exists() and not (d not in taken and is_empty_shell(d)):
        i += 1
        d = root / f"{stamp}_{i}"
    return d


def pick_project(channel: dict, taken: set | None = None,
                 now: datetime | None = None, quota: int = 1,
                 force_new: bool = False) -> dict:
    """Куда писать очередной ролик канала: доделать начатый или начать новый.

    Возвращает {"dir", "mode", "why"}, где mode:
        resume — доделываем незаконченный (самый свежий из годных);
        new    — заводим новую папку с датой;
        done   — на сегодня у канала уже есть готовый ролик.

    Порядок разбора важен и выведен из того, чем платили за ошибки:

    1. Готовый сегодня ролик => done. Иначе повторный запуск автопилота (или
       вторая кнопка за ночь) сделал бы каналу второй и третий ролик за ту же
       ночь — ровно то, чего пользователь не хочет.
    2. Незаконченный проект, самый свежий => resume. До 2026-08-04 автопилот
       безусловно заводил новую папку, и брошенный на 53% ролик оставался
       лежать навсегда, а рядом начинался ещё один с нуля.
    3. Исчерпавший MAX_RESUME попыток => не берём, идём к следующему кандидату.
       Ролик, падающий по системной причине, иначе запер бы канал навсегда.
    4. Ничего не подошло => new.

    taken — папки, уже занятые в ЭТОМ прогоне (при --videos 2 второй ролик
    канала не должен попасть в ту же папку, что и первый).
    """
    taken = taken or set()
    root = _root_of(channel)
    stamp = (now or datetime.now()).strftime("%Y-%m-%d")

    projects = channels_mod.channel_projects(root)
    extra = []
    # Корень канала тоже бывает проектом — в нём лежат ролики, снятые до того,
    # как автопилот начал раскладывать их по датам. Без этой строки такой
    # незаконченный ролик не доделался бы никогда.
    if channels_mod.is_project_dir(root) and root not in projects:
        extra.append(root)
    # И папка с ГОТОВЫМ роликом, даже если по признакам channels.is_project_dir
    # она проектом не считается. Признак там — script.txt или audio/, и папку,
    # где остался только собранный mp4 (сценарий унесли, папку audio почистили),
    # автопилот не видел вовсе: канал считался несделанным, и ночь заводила ему
    # ещё один ролик поверх уже готового.
    try:
        for p in root.iterdir():
            if (p.is_dir() and p not in projects and p not in extra
                    and (p / "output_final.mp4").exists()):
                extra.append(p)
    except OSError:
        pass
    # ПЕРЕСОРТИРОВАТЬ, а не дописать в конец: на настоящих данных корень
    # home-vault оказался самым свежим проектом канала (правился в тот же день),
    # а в конце списка автопилот вместо него брался за папку _stale_3min,
    # брошенную сутками раньше.
    if extra:
        projects = sorted(projects + extra,
                          key=lambda p: (-channels_mod.touched_at(p), p.name))

    # Сколько роликов этого канала УЖЕ доведены до конца сегодня. Считаем по
    # дате самого output_final.mp4, а не «готов вообще»: вчерашний готовый
    # ролик не повод пропускать канал сегодня.
    #
    # Ради этого счётчика всё и затевалось: пользователь спрашивал «он точно не
    # сделает три ролика на один канал?». Одного цикла for мало — повторный
    # запуск автопилота (вторая кнопка за ночь, или ночь, пережившая
    # перезапуск приложения) начинал бы каналу ещё один ролик. Здесь этого не
    # может быть: готовое сегодня видно на диске.
    made = []
    for p in projects:
        if not is_finished(p):
            continue
        try:
            fresh = datetime.fromtimestamp(
                (p / "output_final.mp4").stat().st_mtime).strftime("%Y-%m-%d")
        except OSError:
            continue
        if fresh == stamp:
            made.append(p)
    # Пропуск «сегодня уже сделан» защищает от СЛУЧАЙНОГО дубля: вторая кнопка
    # за ночь, перезапуск приложения. Явную просьбу «сделай новый» он перебивать
    # не должен — иначе защита превращается в запрет делать то, о чём попросили.
    if not force_new and len(made) >= max(1, quota):
        return {"dir": made[0], "mode": "done",
                "why": (f"сегодня уже сделан ({', '.join(p.name for p in made)})"
                        if len(made) == 1 else
                        f"сегодня уже сделано {len(made)} шт. "
                        f"({', '.join(p.name for p in made)})")}

    ref = (now or datetime.now()).timestamp()
    # force_new — человек ЯВНО просит новый ролик, а не докрутку начатого.
    # Докрутка появилась потому, что брошенный на 53% ролик лежал мёртвым
    # грузом, и по умолчанию она правильна. Но она же означает «доделываю
    # старую тему», а иногда нужна именно новая — и тогда навязывать докрутку
    # значит не давать сделать то, о чём попросили. Незаконченное при этом не
    # теряется: оно остаётся на диске и будет доделано в обычном режиме.
    if force_new:
        d = _new_dir(root, stamp, taken)
        return {"dir": d, "mode": "new", "why": f"новый ролик ({d.name})"}

    for p in projects:
        if p in taken or is_finished(p):
            continue
        n = attempts(p)
        if n >= MAX_RESUME:
            continue     # сдались на этом, ищем следующий
        age_d = (ref - channels_mod.touched_at(p)) / 86400
        if age_d > MAX_RESUME_AGE_D:
            continue     # слишком старый, тема протухла
        return {"dir": p, "mode": "resume",
                "why": (f"доделываю начатое ({p.name}, попытка {n + 1} из "
                        f"{MAX_RESUME}, брошен {age_d:.1f} сут назад; "
                        f"{stage_of(p, channel)})")}

    d = _new_dir(root, stamp, taken)
    return {"dir": d, "mode": "new", "why": f"новый ролик ({d.name})"}


# ---------- порядок каналов ----------

def order(channels: list[dict], projects: dict | None = None) -> list[dict]:
    """В каком порядке идти по каналам за ночь.

    Сначала те, где меньше осталось работы. Раньше сортировали просто по длине
    ролика, и это давало не тот порядок: канал с почти готовым 35-минутным
    роликом (осталось отрендерить) уходил в конец очереди за 13-минутным,
    который надо делать с нуля.
    """
    projects = projects or {}
    return sorted(channels,
                  key=lambda c: estimate_s(c, projects.get(c.get("id"))))


def dry_run(channels: list[dict], night_h: float = NIGHT_H, videos: int = 1,
            fit_only: bool = False, now: datetime | None = None,
            force_new: bool = False) -> list[dict]:
    """Что автопилот СОБИРАЕТСЯ делать — без единого побочного действия.

    Ничего не создаёт и не пишет: pick_project возвращает путь, а папку заводит
    уже сам прогон. Нужен и для проверки, и чтобы человек мог посмотреть план
    ночи до того, как уйдёт спать.
    """
    # Порядок считаем ПО ТОМУ ЖЕ разбору папок, каким пойдёт сам прогон:
    # канал с почти готовым роликом должен идти первым, даже если ролик у него
    # самый длинный.
    first = {ch.get("id"): pick_project(ch, None, now, force_new=force_new)
             for ch in channels}
    chans = order(channels, {k: v["dir"] for k, v in first.items()
                             if v["mode"] == "resume"})

    left = night_h * 3600 if night_h > 0 else 0.0
    plan: list[dict] = []
    todo = [(ch, i) for ch in chans for i in range(videos)]
    taken: set = set()
    for pos, (ch, i) in enumerate(todo):
        nm = ch.get("name") or ch.get("id")
        pick = pick_project(ch, taken, now, quota=i + 1, force_new=force_new)
        proj = pick["dir"] if pick["mode"] == "resume" else None
        est = estimate_s(ch, proj)
        row = {"id": ch.get("id"), "channel": nm, "dir": pick["dir"], "n": i,
               "action": pick["mode"], "budget_s": 0.0, "est_s": est,
               "why": pick["why"]}
        if pick["mode"] == "done":
            # Папку готового ролика в taken НЕ кладём: при --videos 2 второй
            # ролик канала должен уметь встать рядом, а не считать её занятой.
            row.update(action="skip", est_s=0.0)
            plan.append(row)
            continue
        taken.add(pick["dir"])
        if fit_only and left and not fits(ch, left, proj):
            row.update(action="skip",
                       why=(f"--fit: нужно ~{est / 3600:.1f} ч, "
                            f"осталось {left / 3600:.1f} ч"))
            plan.append(row)
            continue
        budget = budget_for(ch, left, max(1, len(todo) - pos), proj)
        row["budget_s"] = budget
        plan.append(row)
        if left:
            # Вычитаем ПОТОЛОК, а не оценку. Оценка — среднее, потолок —
            # худший случай, и планировать надо по нему: иначе сумма потолков
            # в плане вылезает за ночь (на проверке 10.6 ч из 10), и последний
            # канал по бумаге получал время, которого нет. Настоящий прогон всё
            # равно пересчитывает остаток по часам, так что уложившийся раньше
            # канал вернёт своё время следующим.
            left = max(0.0, left - budget)
    return plan


# ---------- утренняя сводка ----------

def format_report(results: list[dict], started: datetime,
                  finished: datetime | None = None) -> str:
    """Сводка за ночь. Читает её человек спросонья, поэтому у КАЖДОГО канала
    стоит причина, а не только галочка.

    Раньше сводка кнопки «Автопилот» писала всем неудачам одно
    «не вышло — ищи причину выше», и утром приходилось листать журнал на
    сорок тысяч строк, чтобы понять, канал упал или просто не начинался.
    """
    finished = finished or datetime.now()
    ok = [r for r in results if r.get("file")]
    lines = [
        "=" * 66,
        f"Автопилот: {started:%Y-%m-%d %H:%M} — {finished:%H:%M}",
        f"Готово {len(ok)} из {len(results)}",
        "=" * 66, "",
    ]
    tag = {"resume": "доделан", "new": "с нуля", "skip": "пропущен",
           "done": "уже был готов"}
    for r in results:
        how = tag.get(r.get("mode", ""), r.get("mode", ""))
        if r.get("file"):
            lines.append(f"  + {r['channel']} [{how}]: {r['file']} "
                         f"({r.get('size', 0) / 2**20:.0f} МБ, "
                         f"{r.get('sec', 0) / 60:.0f} мин)")
        else:
            lines.append(f"  - {r['channel']} [{how}]: {r.get('why', '')}")
            # На чём именно встал — отдельной строкой: по ней видно, доделается
            # ли ролик следующей ночью за двадцать минут или беда системная.
            if r.get("dir"):
                lines.append(f"      {r['dir']} — {stage_of(Path(r['dir']))}")
    lines += ["",
              "Незаконченные ролики НЕ выброшены: следующая ночь начнёт с них, "
              f"переиспользуя сценарий, озвучку и ИИ-кадры (до {MAX_RESUME} "
              "попыток на ролик).",
              "Подробности каждого шага — в app.log.",
              "Перед загрузкой на YouTube отметь «Altered content», если в "
              "ролике есть реалистичные ИИ-кадры."]
    return "\n".join(lines)


def format_plan(plan: list[dict]) -> str:
    """План ночи одним куском текста — в журнал перед началом работы."""
    lines = []
    for i, s in enumerate(plan, 1):
        if s["action"] == "skip":
            lines.append(f"  {i}. {s['channel']}: пропуск — {s['why']}")
        else:
            lines.append(
                f"  {i}. {s['channel']}: {s['why']}, "
                f"оценка ~{s['est_s']/3600:.1f} ч, "
                f"потолок {s['budget_s']/3600:.1f} ч")
    return "\n".join(lines)


