# -*- coding: utf-8 -*-
"""Журнал деградаций: что в ролике вышло ХУЖЕ задуманного и почему.

Зачем это вообще. Конвейер построен на запасных путях: не ответил Gemini —
расставим оверлеи регексом, не сгенерировался план Veo — возьмём сток, не
нашлось фото — оставим пометку. Каждый такой откат по отдельности разумен,
он спасает прогон от полной остановки. Но вместе они дают неприятное
свойство: ролик всегда собирается «успешно». Отказ основного пути проходил
рядовой строкой в журнале на сотню строк, и отличить хороший ролик от
деградировавшего можно было только открыв видео и посмотрев его целиком.

Так и терялись длинные ролики: расстановка оверлеев молча уходила на
нарезку по словам, а в конце писалось «готово».

Здесь деградации СОБИРАЮТСЯ и в конце прогона показываются одним списком —
коротко, по-человечески, с причиной и с тем, что можно сделать. Это не
замена журналу, а его итог: журнал отвечает «что происходило», а этот
список — «чего в ролике не хватает и почему».

Записывать сюда стоит только то, что видно ЗРИТЕЛЮ или стоит денег. Не
всякий except — деградация: пропущенный необязательный тег или подобранный
запасной шрифт зрителя не касаются и сюда не идут.
"""
import threading

# Прогон идёт в одном фоновом потоке, но стадии внутри распараллелены
# (раскадровка, Veo, проверка зрением) — писать могут из нескольких разом.
_LOCK = threading.RLock()
_ITEMS: list[dict] = []

# Насколько это бьёт по ролику. Порядок важен: по нему сортируется итог.
LEVELS = ("критично", "заметно", "мелочь")


def reset() -> None:
    """Начало нового прогона. Без этого список копился бы между роликами и
    в итоге показывал чужие беды."""
    with _LOCK:
        _ITEMS.clear()


def degraded(stage: str, what: str, why: str = "", hint: str = "",
             level: str = "заметно") -> None:
    """Записать, что стадия отдала результат хуже задуманного.

    stage — где («Оверлеи», «Раскадровка»); what — что именно вышло хуже,
    словами зрителя, а не кодом; why — причина, как её видно из ошибки;
    hint — что человек может с этим сделать (добавить ключ, сменить тему).
    Одинаковые записи схлопываются со счётчиком: двадцать одинаковых
    провалов Veo — это одна строка «×20», а не двадцать строк.
    """
    if level not in LEVELS:
        level = "заметно"
    with _LOCK:
        for it in _ITEMS:
            if (it["stage"], it["what"], it["level"]) == (stage, what, level):
                it["count"] += 1
                # причину храним ПЕРВУЮ: она обычно и есть корневая, дальше
                # идут её следствия
                return
        _ITEMS.append({"stage": stage, "what": what, "why": why,
                       "hint": hint, "level": level, "count": 1})


def items() -> list[dict]:
    with _LOCK:
        return [dict(x) for x in sorted(_ITEMS,
                                        key=lambda i: LEVELS.index(i["level"]))]


def report() -> str:
    """Итог одной строкой на пункт. Пусто — значит ролик вышел таким, каким
    задуман, и это тоже стоит сказать вслух: иначе тишину не отличить от
    того, что проверка просто не сработала."""
    got = items()
    if not got:
        return ("[Итог] Ролик собран без потерь качества: все основные пути "
                "отработали.")
    lines = [f"[Итог] Ролик собран, но {len(got)} раз(а) пришлось идти "
             "запасным путём — вот что в нём вышло хуже задуманного:"]
    for it in got:
        n = f" ×{it['count']}" if it["count"] > 1 else ""
        line = f"  [{it['level']}] {it['stage']}: {it['what']}{n}"
        if it["why"]:
            line += f" — {it['why']}"
        lines.append(line)
        if it["hint"]:
            lines.append(f"      что делать: {it['hint']}")
    return "\n".join(lines)
