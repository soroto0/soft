# -*- coding: utf-8 -*-
"""Демонстрационный режим: полный софт, но ролики помечены и их немного.

ЧТО ОГРАНИЧЕНО И ПОЧЕМУ ИМЕННО ТАК. Демоверсия должна показать РАБОТУ, а
не огрызок: покупатель обязан увидеть весь путь — разбор ниши, сценарий,
озвучку, кадры, графику, музыку, монтаж, обложку, SEO. Поэтому не
отключено ни одной возможности. Ограничены две вещи:

  1. на каждый ролик кладётся заметная надпись «ДЕМО» — такой ролик
     видно, но выложить его нельзя;
  2. роликов всего DEMO_LIMIT — хватает понять, стабильно ли работает,
     и мало, чтобы пользоваться бесплатно.

ЧЕСТНО О НАДЁЖНОСТИ. Счётчик лежит рядом в обычном файле, и обойти его
человеку со знанием дела ничего не стоит. Это не защита, а граница,
понятная добросовестному покупателю. Настоящая защита — серверная
проверка ключа — стоит своей разработки и поддержки, и заводить её имеет
смысл, когда продажи есть, а не до них.
"""
import json
import time
from pathlib import Path

BASE = Path(__file__).resolve().parent
МЕТКА = BASE / "demo.json"

# Сколько роликов даёт демо. Три — по одному на канал: покупатель видит,
# что каналы РАЗНЫЕ, а это главное отличие софта, и на одном ролике его
# не показать.
DEMO_LIMIT = 3

# Надпись поверх кадра. Держится весь ролик (тип watermark), поэтому
# короткая: длинная строка на 70 минут утомляет даже в демо.
DEMO_WATERMARK = "ДЕМО · Контент-фабрика"


def _прочитать() -> dict:
    try:
        return json.loads(МЕТКА.read_text(encoding="utf-8"))
    except Exception:
        return {}


def включён() -> bool:
    """Демо-режим включён, если рядом лежит demo.json. У купленной копии
    его просто нет — отдельного «ключа активации» не требуется."""
    return МЕТКА.is_file()


def сделано() -> int:
    return int(_прочитать().get("videos", 0) or 0)


def осталось() -> int:
    return max(0, DEMO_LIMIT - сделано())


def можно_ещё() -> tuple[bool, str]:
    """Разрешено ли собирать очередной ролик. -> (да/нет, причина).

    Проверять ПЕРЕД сборкой, а не после: ролик считается часами, и
    сообщить об исчерпании демо в конце — значит потратить чужой вечер
    впустую.
    """
    if not включён():
        return True, ""
    n = осталось()
    if n > 0:
        return True, f"демоверсия: осталось роликов — {n} из {DEMO_LIMIT}"
    return False, (
        f"Демоверсия рассчитана на {DEMO_LIMIT} ролика, и они собраны. "
        "Полная версия снимает и ограничение, и надпись на кадре.")


def засчитать(log=print) -> None:
    """Отметить собранный ролик. Зовётся ПОСЛЕ успешной сборки: если
    прогон оборвался, попытка не должна съедать демо-лимит."""
    if not включён():
        return
    d = _прочитать()
    d["videos"] = сделано() + 1
    d["last"] = time.strftime("%Y-%m-%d %H:%M")
    d.setdefault("first", d["last"])
    try:
        МЕТКА.write_text(json.dumps(d, ensure_ascii=False, indent=2),
                         encoding="utf-8")
    except Exception:
        pass                      # не смогли записать — не повод рушить прогон
    log(f"[Демо] Собрано роликов: {d['videos']} из {DEMO_LIMIT}")


def применить(opts: dict, log=print) -> dict:
    """Наложить ограничения демо на параметры рендера.

    Надпись ставится ПОВЕРХ канальной: у канала свой водяной знак может
    быть задан, и демо не должно его молча стирать — но и прятаться за
    ним не должно.
    """
    if not включён():
        return opts
    opts = dict(opts)
    свой = (opts.get("watermark") or "").strip()
    opts["watermark"] = (f"{DEMO_WATERMARK} · {свой}" if свой
                         else DEMO_WATERMARK)
    log(f"[Демо] На кадр ляжет надпись «{opts['watermark']}». "
        f"Осталось роликов: {осталось()} из {DEMO_LIMIT}")
    return opts
