def _complain(what: str, why: str = "", hint: str = "",
              level: str = "заметно") -> None:
    """Сказать в сводку прогона, что профиль канала применился НЕ ЦЕЛИКОМ.

    Отдельная обёртка, потому что журнала (callback log) здесь нет и быть не
    может: channels.py зовут и из интерфейса, и из ночной цепочки, и из
    планировщика — единого места, куда писать, у них нет. А сводка деградаций
    одна на прогон, и попадает она последними строками журнала.

    Зачем вообще. Профиль КАНАЛА задаёт язык, голос, темп речи, шрифт
    субтитров и долю ИИ-кадров. Любая его потеря — это ролик чужим голосом
    или чужим шрифтом, то есть ровно то, что зритель видит и слышит первым.
    Раньше такая потеря проходила совершенно молча: значение подменялось
    умолчанием, и в журнале не оставалось ни строки.
    """
    try:
        import quality
        quality.degraded("Каналы", what, why=why, hint=hint, level=level)
    except Exception:
        # Сводка — вещь вспомогательная: если её не удалось записать, это не
        # повод ронять запуск ролика.
        pass


def active(chans: list[dict] | None = None) -> list[dict]:
    """Каналы, на которые сейчас делают ролики.

    Отдельной функцией, а не фильтром на месте: перечисление каналов для
    ночи живёт в ТРЁХ файлах (night_plan, autopilot, webapp), и фильтр,
    списанный в каждый из них руками, разъехался бы — план показывал бы
    одно, а ночь делала другое.
    """
    return [c for c in (load() if chans is None else chans)
            if c.get("active", True)]


def series_suffix(channel: dict) -> str:
    """Хвост заголовка для канала с нумерованной серией. Пусто, если серии
    нет. Нужен, потому что у такого канала заголовок вне формата сразу
    выпадает из ряда — зритель узнаёт выпуск именно по «| Findings #N»."""
    name = (channel.get("series") or "").strip()
    if not name:
        return ""
    # Через _num, а не через int(): series_next правят руками в сыром JSON, и
    # int("") роняло сборку заголовка целиком. Молча ставить единицу тоже
    # нельзя — тогда КАЖДЫЙ выпуск канала выйдет с «#1» в заголовке, и
    # зритель перестанет отличать новый ролик от старого.
    return f" | {name} #{_num(channel.get('series_next', 1), 1, 'series_next')}"


def bump_series(channel_id: str) -> None:
    """Сдвинуть номер выпуска после того, как ролик собран."""
    ch = get(channel_id)
    if not ch or not (ch.get("series") or "").strip():
        return
    ch["series_next"] = int(ch.get("series_next", 1)) + 1
    upsert(ch)


# ------------------------------------------------- статистика: что считать своим

def stats_since(channel: dict) -> str:
    """Дата, с которой цифры канала считаются его нынешними. Пусто — все.

    Тонкая обёртка над полем, и всё же отдельная функция. Правило «что
    считать своим» применяется в ТРЁХ местах: при подборе темы, при
    разборе удержания и в накопленной истории (yt_history). Раньше оно
    жило в каждом из них своей копией, а копии расходятся молча — и
    разъехавшись, дали бы худшее из возможного: открытие ролика,
    написанное под аудиторию новой ниши, и тему, выбранную по старой.
    """
    return (channel.get("stats_from") or "").strip()


def in_current_niche(channel: dict, published: str) -> bool:
    """Относится ли ролик к НЫНЕШНЕЙ нише канала.

    published — дата публикации, ISO («2026-07-13» или полная отметка
    времени); сравнение идёт по первым десяти символам, поэтому годится
    и то и другое.

    Зачем вообще отсекать. Ролики прежней ниши остаются на канале и
    продолжают отдавать цифры — и цифры эти врут дважды: как пример
    удачной темы и как замер удержания. Живой случай (abyss, 2026-08-08):
    ролик про сетевую страшилку с 127 просмотрами и досмотром 32%
    оставался лучшим на канале и подавался сценаристу как образец, хотя
    канал уже месяц про техногенные катастрофы. Он был единственным, у
    кого вообще были просмотры, — то есть перевешивал всю новую нишу в
    одиночку и тянул канал назад.

    Ролик без даты СЧИТАЕТСЯ СВОИМ. Отбрасывать по отсутствию данных
    нельзя: так из разбора тихо исчезнет настоящий свежий ролик, у
    которого просто не пришла дата, и канал останется вовсе без образцов.
    """
    since = stats_since(channel)
    if not since:
        return True
    day = (published or "")[:10]
    return not day or day >= since


def _read() -> tuple[list[dict], str]:
    """Разбор channels.json: (профили, причина отказа).

    ПОЧЕМУ ДВА ЗНАЧЕНИЯ, А НЕ ПРОСТО СПИСОК. Раньше и «файла ещё нет», и
    «файл испорчен» давали один и тот же пустой список — и это была не
    мелочь, а потеря всех каналов разом. Дальше по коду пустой список
    означает «каналов не заведено»: upsert() дописывал к НЕМУ один профиль и
    сохранял результат целиком, то есть один битый байт в файле стирал
    остальные каналы навсегда; автопилот на пустом списке тихо не делал за
    ночь ничего; выбранный канал переставал находиться, и ролик уезжал в
    сборку с умолчаниями — чужим языком, чужим голосом, чужим шрифтом.

    Причина отказа возвращается отдельно, чтобы вызывающий сам решил: читать
    (интерфейсу лучше показать пустой список, чем белый экран) можно, а
    ПИСАТЬ поверх нечитаемого файла — нельзя.
    """
    try:
        # utf-8-sig, а не utf-8: три байта BOM в начале файла превращали
        # ЛЮБОЙ channels.json в «испорченный». Это не теория — так вело себя
        # всё, что пишет Windows: Set-Content -Encoding UTF8 в PowerShell 5.1
        # (им dist_pack.ps1 клал channels.example.json покупателю), «Блокнот»
        # с выбором «UTF-8 с BOM», выгрузка из Excel. Замер на раздаче:
        # покупатель делает ровно то, что велит README — копирует
        # channels.example.json в channels.json — и получает
        # «Unexpected UTF-8 BOM ... (char 0)», ноль каналов в окне И отказ
        # завести канал через интерфейс (upsert не пишет поверх нечитаемого
        # файла). То есть тупик на первом же шаге, причём невидимый: в
        # редакторе файл выглядит правильным. utf-8-sig съедает BOM, если он
        # есть, и ничего не меняет, если его нет.
        raw = CHANNELS_FILE.read_text(encoding="utf-8-sig")
    except FileNotFoundError:
        return [], ""          # каналы ещё не заведены — это норма
    except OSError as e:
        return [], f"{CHANNELS_FILE.name} не читается: {e}"
    try:
        data = json.loads(raw)
    except ValueError as e:
        return [], f"{CHANNELS_FILE.name} испорчен (не разбирается как JSON): {e}"
    if not isinstance(data, list):
        return [], (f"{CHANNELS_FILE.name} испорчен: ожидался список каналов, "
                    f"а лежит {type(data).__name__}")
    out, skipped = [], 0
    for rec in data:
        if isinstance(rec, dict) and rec.get("id"):
            out.append({**DEFAULTS, **rec})
        else:
            skipped += 1
    if skipped:
        # Запись без id — это канал, который пропал из интерфейса и из ночного
        # плана: его ролики не снимаются, а сказать об этом было некому.
        _complain(f"в channels.json пропущено записей без id: {skipped}",
                  why="у профиля канала нет поля id — такая запись нигде не "
                      "числится каналом",
                  hint="открой channels.json и допиши id пропавшим каналам",
                  level="критично")
    return out, ""


def load() -> list[dict]:
    """Все профили. Пустой список — каналы ещё не заведены (это норма).

    Испорченный файл нормой НЕ считается: он тоже отдаёт пустой список (иначе
    интерфейс не открылся бы и чинить было бы нечем), но громко жалуется, а
    запись поверх такого файла запрещена — см. _read и upsert.
    """
    chans, broken = _read()
    if broken:
        _complain("профили каналов не прочитаны — язык, голос, шрифт и стиль "
                  "взяты умолчательные",
                  why=broken,
                  hint="почини channels.json (рядом мог остаться "
                       "channels.json.tmp от прерванной записи) — пока он "
                       "битый, сохранение канала будет отказывать, чтобы не "
                       "затереть остальные",
                  level="критично")
    return chans


def save(channels: list[dict]) -> None:
    with _FILE_LOCK:
        tmp = CHANNELS_FILE.with_name(CHANNELS_FILE.name + ".tmp")
        tmp.write_text(
            json.dumps(channels, ensure_ascii=False, indent=2), encoding="utf-8")
        os.replace(tmp, CHANNELS_FILE)


def get(channel_id: str) -> dict | None:
    for ch in load():
        if ch["id"] == channel_id:
            return ch
    return None


def upsert(channel: dict) -> list[dict]:
    """Добавить или обновить профиль по его id. Частичное обновление (как
    из формы UI — присылает не все ~26 полей) мёрджится ПОВЕРХ уже
    сохранённой записи, а не поверх DEFAULTS — иначе любое поле, которое
    форма не прислала (topic_formula, used_topics, script_extra и т.д.),
    тихо откатывалось на дефолт при каждом редактировании канала."""
    cid = str(channel.get("id", "")).strip()
    if not cid:
        raise ValueError("у канала должен быть id")
    # Чтение и запись — под одним замком: иначе между load() и save() успевает
    # вклиниться upsert из фонового потока, и его правка теряется целиком.
    with _FILE_LOCK:
        chans, broken = _read()
        if broken:
            # ОТКАЗЫВАЕМСЯ ПИСАТЬ. Прочитать файл не вышло, значит в chans
            # пусто — и сохранение записало бы в channels.json ровно один
            # профиль, стерев остальные каналы вместе с их темами, формулами
            # ниш и списком уже снятых тем. Восстанавливать это неоткуда.
            # Лучше отказ, который человек увидит сразу, чем «сохранено».
            raise RuntimeError(
                f"Профиль не сохранён: {broken}. Записать сейчас — значит "
                f"затереть остальные каналы; почини {CHANNELS_FILE.name} "
                "(или удали его, если каналов и правда нет) и повтори")
        for i, ch in enumerate(chans):
            if ch["id"] == cid:
                chans[i] = {**ch, **channel, "id": cid}
                break
        else:
            chans.append({**DEFAULTS, **channel, "id": cid})
        save(chans)
    return chans


def _num(value, default, field: str = ""):
    """Число из профиля, каким бы его ни ввели руками.

    Профиль правится как СЫРОЙ JSON в окне prompt (ui/app.js, editChannel),
    поэтому в rate/sub_width/ai_ratio легко попадает "" или "-3%" вместо
    числа. Раньше int("") валил apply_to_params с ValueError — то есть
    опечатка в форме канала роняла весь запуск ещё до первого кадра, и по
    сообщению было не понять, что дело в профиле.

    Но и молчать про подмену нельзя. Человек ЧТО-ТО в поле написал, а ролик
    вышел с умолчанием: rate — это темп речи (слышно сразу), sub_width —
    ширина строки субтитров, ai_ratio — доля рисованных кадров, minutes —
    длина ролика. Отличаем ПУСТОЕ поле («ничего не навязываю», молчим) от
    НЕПОНЯТНОГО значения («хотел, но не вышло» — говорим вслух).
    """
    try:
        return type(default)(value)
    except (TypeError, ValueError):
        if field and value is not None and str(value).strip():
            _complain(f"настройка канала «{field}» не понята и заменена "
                      f"умолчанием {default!r}",
                      why=f"в профиле записано {value!r}, а нужно число",
                      hint=f"впиши в «{field}» число (профиль правится как "
                           "сырой JSON, кавычки и знаки % туда не годятся)")
        return default


def projects_dir(channel: dict) -> Path:
    """Папка, где лежат проекты этого канала. Разводим их по разным папкам,
    чтобы список проектов в интерфейсе не превращался в кашу из трёх каналов
    и чтобы случайно не отрендерить ролик одного канала в стиле другого."""
    folder = (channel.get("folder") or "").strip()
    return Path(folder) if folder else BASE / channel["id"]


def is_project_dir(p: Path) -> bool:
    """Похожа ли папка на проект (в ней уже начат ролик).

    Признак ровно тот же, по которому интерфейс строит список проектов
    (webapp.get_state). Общий он СПЕЦИАЛЬНО: пока «проект» для списка и
    «проект» для выбора канала считались по-разному, переключение канала
    вставало на папку, которой в списке нет, — а значит человек не видел,
    куда его увели.
    """
    try:
        # Служебные папки с подчёркивания — НЕ проекты. Признак «есть
        # script.txt» слишком широкий: любая папка, куда сложили старые
        # файлы, тут же становилась «самым свежим проектом» и подставлялась
        # в рабочий путь при выборе канала. Так и вышло: архив
        # _старое_из_корня подменил собой проект канала abyss.
        if p.name.startswith(("_", ".")):
            return False
        return p.is_dir() and ((p / "script.txt").exists()
                               or (p / "audio").exists())
    except OSError:
        return False


def _touched_at(p: Path) -> float:
    """Когда в проекте последний раз что-то делали.

    Смотрим не на одну лишь папку проекта: её mtime меняется, только когда
    в НЕЙ создают файл, а озвучка, кадры и рендер ложатся внутрь подпапок
    (audio/, storyboard/, video/). По одному корню почти доделанный ролик
    выглядел бы таким же старым, как брошенная пустышка, — и «самым свежим»
    оказался бы не тот.
    """
    times = []
    try:
        times.append(p.stat().st_mtime)
        for child in p.iterdir():
            try:
                times.append(child.stat().st_mtime)
            except OSError:
                pass
    except OSError:
        pass
    return max(times, default=0.0)


def touched_at(p: Path) -> float:
    """Публичное имя для _touched_at: тем же признаком «когда трогали» ночной
    планировщик решает, какой из незаконченных роликов доделывать первым.
    Считать это второй раз у себя нельзя — разойдётся с тем, что показывает
    список проектов, и человек увидит в интерфейсе не ту папку, в которую
    ночью писал автопилот."""
    return _touched_at(p)


def channel_projects(root: Path) -> list[Path]:
    """Проекты внутри папки канала, самый свежий первым.

    Порядок по свежести, а не по имени: папки называются датой
    (2026-08-04, 2026-08-04_2 — см. night_plan.pick_project), при
    сортировке по имени сегодняшний ролик оказывался бы последним, а
    интерфейс показывает только первые восемь.
    """
    try:
        subs = [p for p in root.iterdir() if is_project_dir(p)]
    except FileNotFoundError:
        # На канале ещё не начинали ни одного ролика — папки просто нет.
        # Это норма и молчать здесь правильно.
        return []
    except OSError as e:
        # А вот это НЕ норма, и раньше выглядело точно так же. Пустой список
        # означает «незаконченных роликов нет»: latest_project возвращает
        # корень канала, и «Генерировать видео» начинает НОВЫЙ ролик поверх
        # почти готового — сценарий, озвучка и сотни ИИ-кадров остаются
        # лежать в подпапке нетронутыми (так уже потеряли два ролика за день).
        _complain("папка канала не читается — незаконченные ролики не "
                  "найдены, работа может начаться заново вместо продолжения",
                  why=f"{root}: {e}",
                  hint="проверь, доступна ли папка канала (диск на месте, "
                       "путь в поле folder верный)",
                  level="критично")
        return []
    return sorted(subs, key=lambda p: (-_touched_at(p), p.name))


def latest_project(root: Path) -> Path:
    """Какую папку считать текущим проектом канала.

    Самый свежий проект-подпапку, а если подпапок-проектов нет — сам root:
    у канала, где ещё ничего не снимали, проект и есть корень канала.

    Зачем это вообще нужно: ролики лежат в подпапках с датой
    (abyss/2026-08-04), их заводит автопилот, а выбор канала ставил рабочей
    папкой КОРЕНЬ канала. Человек выбирал канал, жал «Генерировать видео» —
    и вместо продолжения почти готового ролика начинался новый с нуля, а
    сценарий, озвучка и сто семьдесят ИИ-кадров оставались нетронутыми в
    подпапке. За один день так потеряли два ролика.
    """
    subs = channel_projects(root)
    return subs[0] if subs else root


def apply_to_params(channel: dict, p: dict) -> dict:
    """Наложить настройки канала на параметры запуска из интерфейса.

    Канал ЗАДАЁТ, а не предлагает: язык, жанр, голос и визуальный стиль
    берутся из профиля. Иначе достаточно один раз забыть переключить
    выпадающий список — и ролик выйдет чужим голосом на чужом языке.
    Пустые поля профиля ничего не навязывают.

    В out["channel_locked"] складываются имена полей, которые профиль прибил
    гвоздями. Это читает «Разнообразие» (webapp: _tts_step, _render_opts),
    чтобы случайный «почерк проекта» не перебивал постоянные признаки
    канала — и при этом продолжал менять всё остальное."""
    out = dict(p)
    locked = []
    # МОНТАЖ тоже принадлежит каналу. Раньше список кончался на шрифте, и
    # темп, цветокор, пауза между оверлеями и звуки в профиль просто не
    # проходили — все три канала брали один умолчательный монтаж, и ролики
    # с разных каналов выглядели снятыми одним человеком. Различались только
    # субтитры, голос и палитра.
    for key in ("lang", "tone", "visual_style", "sub_style", "sub_size",
                "sub_font", "intensity", "look", "min_gap", "sfx",
                "script_shape",
                # resolution — свойство КАНАЛА, а не прогона. Канал Shorts
                # обязан отдавать 1080x1920 всегда, а не когда кто-то
                # вспомнит переключить формат в окне. Отсюда же берётся
                # соотношение сторон заказываемых кадров: горизонтальный
                # кадр обрезать до вертикали нельзя, Veo ставит предмет в
                # середину широкого кадра.
                "resolution",
                # palette — САМОЕ важное для непохожести каналов, и её тут не
                # было. По ней разведены склейки и движение кадра
                # (render.PALETTES), воздух кадра (core.ATMOSPHERE) и звук
                # (core.SOUND_PALETTES). Всё это написано и по-настоящему
                # различается: у harsh преобладает жёсткая склейка и
                # статичный кадр, у warm наплывы и панорамы, у
                # contemplative растворения и медленный дрейф. Но ключ не
                # доезжал до параметров рендера, и все три канала шли
                # общим пулом с общими весами — отсюда «монтаж трёх каналов
                # очень похож».
                "palette",
                # Плёночные эффекты — тоже признак канала, а не разовая
                # галка. В рендере они давно есть (sand — пыльная взвесь в
                # луче, stars — искры, light_leak — засветка, bloom —
                # свечение), но в профиль не проходили, и канал не мог их
                # закрепить за собой.
                "sand", "stars", "dust", "flicker", "bloom", "light_leak",
                "grain", "vignette", "letterbox"):
        v = channel.get(key)
        # Отбрасываем ПУСТОТУ, а не «ложь». Проверка на истинность съедала
        # осмысленные значения: sfx=False (канал сознательно без звуков)
        # молча не применялся, как и min_gap=0. Для строк пустая строка
        # по-прежнему ничего не навязывает — это и есть «поле не заполнено».
        if v is None or (isinstance(v, str) and not v.strip()):
            continue
        out[key] = v
        locked.append(key)
    if channel.get("ai_ratio"):
        # Это ДОЛЯ, от 0 до 1. В сыром JSON легко написать 85 вместо 0.85, и
        # такое число тихо уезжало дальше по конвейеру: доля ИИ-планов
        # считается умножением, и 85 означает «генерировать всё подряд» —
        # безлимитный Veo это молча съест, а счёт придёт за 85 роликов.
        ratio = _num(channel["ai_ratio"], float(DEFAULTS["ai_ratio"]), "ai_ratio")
        out["ai_ratio"] = min(1.0, max(0.0, ratio / 100 if ratio > 1 else ratio))
    # Субтитры — единственная настройка, которую профиль раньше перебивал
    # БЕЗУСЛОВНО: человек снимал галочку «Вшить субтитры», а они всё равно
    # вжигались, потому что в профиле стоит subs_on=True по умолчанию.
    # Профиль задаёт умолчание канала, а не отменяет выбор, сделанный прямо
    # сейчас. Поэтому «нет» с любой стороны означает «нет»: снятая галочка
    # выключает субтитры, а канал с subs_on=False не даёт их включить.
    #
    # ОТСУТСТВИЕ ключа «subs» — это НЕ «нет», а «выбора не делали»: тогда
    # решает профиль. На это опирается ночной автопилот (webapp.Api.autopilot
    # выбрасывает ключ из параметров ночи) — и опирается не от красоты:
    # с 07.08 по 12.08 галочка на странице стояла снятой в самой разметке, её
    # состояние уезжало и в ночные прогоны, и 20 роликов подряд вышли вообще
    # без субтитров при subs_on: true у всех каналов. Менять умолчание True
    # на False здесь нельзя — это ровно та же поломка, только изнутри.
    out["subs"] = (bool(p.get("subs", True))
                   and bool(channel.get("subs_on", True)))
    # мусор в поле не должен обнулять ширину, выбранную в интерфейсе
    if _num(channel.get("sub_width"), 0, "sub_width"):
        out["sub_width"] = _num(channel["sub_width"], 0)
    if channel.get("voice"):
        out["voice"] = channel["voice"]
        out["rate"] = f"{_num(channel.get('rate', 0), 0, 'rate'):+d}%"
        out["pitch"] = _num(channel.get("pitch", 0), 0, "pitch")
        # Здесь стояло out["randomize"] = False — «чтобы разнообразие не
        # перебило голос канала». Но тот же флаг отвечает ещё за
        # интенсивность монтажа, цветокор и эффекты, и выключение ради
        # голоса делало ВСЕ ролики канала визуально одинаковыми — ровно
        # против того, зачем разнообразие вводили. Запираем именно голос и
        # темп, остальное продолжает меняться от ролика к ролику.
        locked += ["voice", "rate", "pitch"]
    if channel.get("minutes"):
        # длина уезжает в расчёт сценария, где ждут число, а не строку "45"
        out.setdefault("minutes",
                       _num(channel["minutes"], DEFAULTS["minutes"], "minutes"))
    out["channel_locked"] = locked
    return out
